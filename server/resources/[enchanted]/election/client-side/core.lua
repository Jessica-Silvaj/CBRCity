-----------------------------------------------------------------------------------------------------------------------------------------
-- DYNAMIC:OPEN
-----------------------------------------------------------------------------------------------------------------------------------------
AddEventHandler("election:Open",function()
	if lib.callback.await("election:Check",false) then
		SetNuiFocus(true,true)
		TransitionToBlurred(1000)
		TriggerEvent("hud:Active",false)
		SendNUIMessage({ Action = "Open" })
	end
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- CLOSE
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterNUICallback("Close",function(Data,Callback)
	SetNuiFocus(false,false)
	TransitionFromBlurred(1000)
	TriggerEvent("hud:Active",true)

	Callback(true)
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- CONFIG
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterNUICallback("Config",function(Data,Callback)
	Callback(lib.callback.await("election:Config",false))
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- VOTE
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterNUICallback("Vote",function(Data,Callback)
	Callback(lib.callback.await("election:Update",false,Data.Candidate,Data.Vote))
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- LOCATIONS
-----------------------------------------------------------------------------------------------------------------------------------------
local Locations = {
	vec3(140.37,-1032.65,29.35)
}
-----------------------------------------------------------------------------------------------------------------------------------------
-- THREADSERVERSTART
-----------------------------------------------------------------------------------------------------------------------------------------
CreateThread(function()
	for Number,v in pairs(Locations) do
		exports.target:AddCircleZone("Election:"..Number,v,1.25,{
			name = "Election:"..Number,
			heading = 0.0,
			useZ = true
		},{
			shop = Number,
			Distance = 1.25,
			options = {
				{
					event = "election:Open",
					tunnel = "client",
					label = "Votar"
				}
			}
		})
	end
end)
