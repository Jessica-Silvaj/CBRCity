CreateThread(function()
	for Number,v in pairs(Location) do
		exports.target:AddCircleZone("Bank:"..Number,v,1.0,{
			name = "Bank:"..Number,
			heading = 0.0,
			useZ = true
		},{
			Distance = 1.0,
			options = {
				{
					event = "Bank",
					label = "Abrir",
					tunnel = "client"
				}
			}
		})
	end

	for Number,v in pairs(ATMList) do
		exports.target:AddCircleZone("BankATM:"..Number,v,1.0,{
			name = "BankATM:"..Number,
			heading = 0.0,
			useZ = true
		},{
			Distance = 1.0,
			options = {
				{
					event = "Bank",
					label = "Abrir",
					tunnel = "client"
				},
				{
					event = "eletronics:openSystem",
					label = "Roubar",
					tunnel = "client"
				}
			}
		})
	end
