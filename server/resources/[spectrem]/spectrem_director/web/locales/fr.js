  function translateText(source) {
    if (typeof source !== "string" || !source) return source;
    const tokens = [];
    let result = source.replace(protectedToken, (token) => `\uE000${tokens.push(token) - 1}\uE001`);
    for (const [sourcePhrase, frenchPhrase] of phraseEntries) {
      result = result.replace(new RegExp(escapeRegExp(sourcePhrase), "gi"), (match) => matchCase(match, frenchPhrase));
    }
    result = result.replace(wordPattern, (_match, prefix, word) => {
      const translated = words[word.toLocaleLowerCase("fr")] || word;
      return prefix + matchCase(word, translated);
    });
    result = polishFrench(result);
    return result.replace(/\uE000(\d+)\uE001/g, (_match, index) => tokens[Number(index)] || "");
  }

